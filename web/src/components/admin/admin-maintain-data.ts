export function formatBalanceWithSide(amountFormatted: string, side: BalanceSide): string {
  const cleaned = amountFormatted.replace(/\s*(DR|CR)\s*$/i, "").trim();
  const base = cleaned || "₦0.00";
  return `${base} ${side}`;
}

export function parseNairaNumeric(formatted: string): number {
  const cleaned = formatted.replace(/[^\d.-]/g, "");
  const parsed = Number.parseFloat(cleaned);
  return Number.isFinite(parsed) ? parsed : 0;
}

export function formatNairaAmount(amount: number): string {
  const abs = Math.abs(amount);
  const formatted = abs.toLocaleString("en-NG", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  });
  return amount < 0 ? `-₦${formatted}` : `₦${formatted}`;
}

