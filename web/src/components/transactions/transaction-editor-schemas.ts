export type EditorLayoutKind =
  | "line-items"
  | "settlement"
  | "journal-grid"
  | "payroll-slip"
  | "inventory-bom"
  | "reconcile-clear"
  | "workflow-note";

export interface TransactionExtraField {
  readonly key: string;
  readonly label: string;
  readonly type: "text" | "select" | "date" | "number" | "textarea";
  readonly options?: readonly string[];
  readonly placeholder?: string;
  readonly defaultValue?: string;
  readonly includeInSimple?: boolean;
  readonly tab: "details" | "accounting" | "settlement";
}

export interface TransactionEditorBlueprint {
  readonly typeId: TransactionTypeId;
  readonly editorLayout: EditorLayoutKind;
  readonly counterpartyLabel: string;
  readonly counterpartyPlaceholder: string;
  readonly counterpartySuggestions: readonly string[];
  readonly referenceLabel: string;
  readonly defaultAccountOptions: readonly string[];
  readonly defaultDebitAccount: string;
  readonly defaultCreditAccount: string;
  readonly defaultPaymentMethod: string;
  readonly paymentMethods: readonly string[];
  readonly supportsVat: boolean;
  readonly defaultVatEnabled: boolean;
  readonly supportsWht: boolean;
  readonly defaultWhtRatePct: 0 | 2 | 5 | 10;
  readonly simpleIntro: string;
  readonly fullIntro: string;
  readonly primaryActionLabel: string;
  readonly extraFields: readonly TransactionExtraField[];
}

